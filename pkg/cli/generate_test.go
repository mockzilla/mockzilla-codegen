func TestOutputDiagnostics(t *testing.T) {
	t.Parallel()

	list := []codegen.Diagnostic{
		{Severity: codegen.SeverityWarning, Code: "filter-empty", Message: "the filter removed every operation"},
		{Severity: codegen.SeverityInfo, Code: "prune-skipped", File: "/work/api.yaml", Message: "nothing is pruned"},
		{Severity: codegen.SeverityError, Code: "build-issue", File: "https://example.com/api.yaml", Line: 3, Col: 1, Pointer: "/paths", Message: "bad"},
	}
	tests := []struct {
		name      string
		isVerbose bool
		want      string
	}{
		{
			name: "Warnings and errors",
			want: "warning filter-empty: the filter removed every operation\n" +
				"https://example.com/api.yaml:3:1: error build-issue: bad [/paths]\n",
		},
		{
			name:      "Verbose adds info",
			isVerbose: true,
			want: "warning filter-empty: the filter removed every operation\n" +
				"api.yaml: info prune-skipped: nothing is pruned\n" +
				"https://example.com/api.yaml:3:1: error build-issue: bad [/paths]\n",
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			var stderr strings.Builder
			o := &output{cmd: &Command{Stderr: &stderr}, dir: "/work"}
			o.diagnostics(list, tc.isVerbose)

			assert.Equal(t, tc.want, stderr.String())
		})
	}
}

func TestOutputVerdict(t *testing.T) {
	t.Parallel()

	warning := codegen.Diagnostic{Severity: codegen.SeverityWarning}
	tests := []struct {
		name       string
		list       []codegen.Diagnostic
		isStrict   bool
		wantCode   int
		wantStderr string
	}{
		{name: "Info only", list: []codegen.Diagnostic{{Severity: codegen.SeverityInfo}}, isStrict: true},
		{name: "Warnings without -strict", list: []codegen.Diagnostic{warning}},
		{
			name:       "Warnings with -strict",
			list:       []codegen.Diagnostic{warning, warning},
			isStrict:   true,
			wantCode:   ExitFail,
			wantStderr: "mockzilla-codegen: failed on 2 warnings\n",
		},
		{
			name:       "One error",
			list:       []codegen.Diagnostic{warning, {Severity: codegen.SeverityError}},
			wantCode:   ExitFail,
			wantStderr: "mockzilla-codegen: failed on 1 error\n",
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			var stderr strings.Builder
			o := &output{cmd: &Command{Stderr: &stderr}}

			assert.Equal(t, tc.wantCode, o.verdict(tc.list, tc.isStrict))
			assert.Equal(t, tc.wantStderr, stderr.String())
		})
	}
}

