func TestGenerateWithExtraFileSymbol(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name     string
		path     string
		packages string
		text     string
		want     string
	}{
		{
			name: "Name of a part in the folder of the file, bare",
			path: "./api/register.go",
			text: "var New = {{symbol `server.router` `NewRouter`}}",
			want: "package api\n\nvar New = NewRouter\n",
		},
		{
			name: "Name of a part in another folder, with its import",
			text: "var New = {{symbol `server.router` `NewRouter`}}",
			want: "package app\n\nimport \"example.com/work/api\"\n\nvar New = api.NewRouter\n",
		},
		{
			name:     "Name of a part in a folder with a package name of its own",
			packages: "{./api: petapi}",
			text:     "var New = {{symbol `server.router` `NewRouter`}}",
			want:     "package app\n\nimport petapi \"example.com/work/api\"\n\nvar New = petapi.NewRouter\n",
		},
		{
			name: "Name of a part whose package name another import of the file holds",
			text: "var Get = {{import `example.com/other/api`}}.Get\n\nvar New = {{symbol `server.router` `NewRouter`}}",
			want: "package app\n\nimport (\n\t\"example.com/other/api\"\n\tapi2 \"example.com/work/api\"\n)\n\nvar Get = api.Get\n\nvar New = api2.NewRouter\n",
		},
		{
			name: "Type of a model part",
			text: "var Pets []{{symbol `models.types` `Pet`}}",
			want: "package app\n\nimport \"example.com/work/models\"\n\nvar Pets []models.Pet\n",
		},
		{
			name: "Name another extra file declares, in another folder",
			text: "var All = {{symbol `./api/names.go` `Names`}}",
			want: "package app\n\nimport \"example.com/work/api\"\n\nvar All = api.Names\n",
		},
		{
			name: "Unexported name another extra file declares, in the folder of the file",
			path: "./api/register.go",
			text: "var All = {{symbol `./api/names.go` `names`}}",
			want: "package api\n\nvar All = names\n",
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			path := cmp.Or(tc.path, "./app/register.go")
			res, err := generateExtra(t, "package: api\n"+
				"output: {file: ./api/gen.go, packages: "+cmp.Or(tc.packages, "{}")+", files: {./models/models.go: [models]}}\n"+
				"server: {framework: chi}\n"+
				"extra-files: {"+path+": {file: ./register.tmpl}, ./api/names.go: 'var Names, names []string'}\n",
				map[string]string{"register.tmpl": tc.text})

			require.NoError(t, err)
			i := slices.IndexFunc(res.Files, func(f File) bool { return slices.Equal(f.Parts, []string{path}) })
			require.GreaterOrEqual(t, i, 0)
			assert.Equal(t, "// Code generated by mockzilla-codegen. DO NOT EDIT.\n\n"+tc.want, string(res.Files[i].Content))
		})
	}
}

func TestRenderExtraOfATypeExprCannotWrite(t *testing.T) {
	t.Parallel()

	cfg, err := config.Parse([]byte("output: {file: ./api/gen.go}\n"), "/work")
	require.NoError(t, err)
	lay, err := layout.Plan(cfg, []layout.Part{{ID: gomodel.PartTypes}}, layout.Module{Path: "example.com/work", Dir: "/work"})
	require.NoError(t, err)

	_, err = renderExtra("./x.go", "{{expr .}}", TypeRef{Name: "Option[Pet]", Package: "opt", ImportPath: "example.com/opt"}, gocode.NewScope(lay.Files[0], lay))

	require.ErrorIs(t, err, ErrExtraFile)
	require.ErrorIs(t, err, errTypeRef)
	assert.EqualError(t, err, `extra file: render: template: ./x.go:1:2: executing "./x.go" at <expr .>: error calling expr: `+
		`type "Option[Pet]" of example.com/opt is no identifier, nor a pointer, slice, array, map or channel around one`)
}

func TestGenerateWithExtraFilesErrors(t *testing.T) {
	t.Parallel()

	const apart = "package: api\noutput: {file: ./api/gen.go, files: {./models/models.go: [models]}}\nserver: {framework: chi}\n"
	tests := []struct {
		name    string
		cfg     string
		extra   string
		wantErr error
		wantMsg string
	}{
		{
			name:    "Template that does not parse",
			extra:   `"{{if}}"`,
			wantErr: ErrExtraFile,
			wantMsg: "./x.go: extra file: load templates: ./x.go: template: ./x.go:1: missing value for if",
		},
		{
			name:    "Template that asks for a field the data has not",
			extra:   `"var X = {{.Owner}}"`,
			wantErr: ErrExtraFile,
			wantMsg: `./x.go: extra file: render: template: ./x.go:1:10: executing "./x.go" at <.Owner>: can't evaluate field Owner in type *codegen.API`,
		},
		{
			name:    "Template that writes no declarations",
			extra:   `"x := 1"`,
			wantErr: ErrExtraFile,
			wantMsg: "./x.go: extra file: parse generated code: ./x.go:1:1: expected declaration, found x\n>    1 | x := 1\n",
		},
		{
			name:    "Template that names a part the config does not write",
			extra:   `"var X = {{symbol \"client.client\" \"New\"}}"`,
			wantErr: ErrExtraFile,
			wantMsg: `./x.go: extra file: render: template: ./x.go:1:10: executing "./x.go" at <symbol "client.client" "New">: error calling symbol: symbol "New": the config writes no part "client.client"`,
		},
		{
			name:    "Template that asks import for no path",
			extra:   `'{{import ""}}'`,
			wantErr: ErrExtraFile,
			wantMsg: `./x.go: extra file: render: template: ./x.go:1:2: executing "./x.go" at <import "">: error calling import: import without a path`,
		},
		{
			name:    "Template that asks symbol for a name that is no identifier",
			extra:   `'{{symbol "server.router" "NewRouter()"}}'`,
			wantErr: ErrExtraFile,
			wantMsg: `./x.go: extra file: render: template: ./x.go:1:2: executing "./x.go" at <symbol "server.router" "NewRouter()">: ` +
				`error calling symbol: symbol "NewRouter()" of server.router is no identifier`,
		},
		{
			name:    "Template that asks symbol for an unexported name of another folder",
			cfg:     apart + "extra-files: {./app/x.go: '{{symbol \"models.types\" \"pet\"}}'}\n",
			wantErr: ErrExtraFile,
			wantMsg: `./app/x.go: extra file: render: template: ./app/x.go:1:2: executing "./app/x.go" at <symbol "models.types" "pet">: ` +
				"error calling symbol: symbol pet of models.types is not exported, so no file outside the folder of ./models/models.go can use it",
		},
		{
			name:    "Template file that is missing",
			extra:   "{file: ./missing.tmpl}",
			wantErr: ErrTemplateFile,
			wantMsg: `read template file: extra-files["./x.go"]: open `,
		},
		{
			name:    "Extra file that uses a type of a folder which imports its own",
			cfg:     apart + "extra-files: {./models/x.go: 'var Options {{expr (index .Operations 0).RequestOptions}}'}\n",
			wantErr: layout.ErrImportCycle,
			wantMsg: "import cycle: api -> models -> api (server.service uses example.com/work/models, ./models/x.go uses example.com/work/api)",
		},
		{
			name:    "Extra file that names a function of a folder which imports its own",
			cfg:     apart + "extra-files: {./models/x.go: 'var New = {{symbol \"server.router\" \"NewRouter\"}}'}\n",
			wantErr: layout.ErrImportCycle,
			wantMsg: "import cycle: api -> models -> api (server.service uses example.com/work/models, ./models/x.go uses example.com/work/api)",
		},
		{
			name:    "Extra file that imports its own package",
			cfg:     apart + "extra-files: {./api/x.go: 'var New = {{import \"example.com/work/api\"}}.NewRouter'}\n",
			wantErr: layout.ErrImportCycle,
			wantMsg: "import cycle: api -> api (./api/x.go uses example.com/work/api)",
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			_, err := generateExtra(t, cmp.Or(tc.cfg, "server: {framework: chi}\nextra-files: {./x.go: "+tc.extra+"}\n"), nil)

			require.ErrorIs(t, err, tc.wantErr)
			assert.Contains(t, err.Error(), tc.wantMsg)
		})
	}
}
