// routesTemplate lists the routed operations and builds the router, from a package of its own.
const routesTemplate = `{{- $http := import "net/http"}}
// Routes maps every routed operation to its method and path.
var Routes = map[string][2]string{
{{- range .Operations}}{{if .IsRouted}}
	{{quote .ID}}: {{"{"}}{{quote .Method}}, {{quote .Path}}{{"}"}},
{{- end}}{{end}}
}

// Handler returns the router of svc.
func Handler(svc {{expr .Service}}) {{$http}}.Handler {
	return {{symbol "server.router" "NewRouter"}}(svc)
}
`

// generateExtra runs the store spec with cfg in a module folder that holds the files.
func generateExtra(t *testing.T, cfg string, files map[string]string) (*Result, error) {
	t.Helper()

	dir := workDir(t)
	for name, text := range files {
		require.NoError(t, os.MkdirAll(filepath.Dir(filepath.Join(dir, name)), 0o750))
		require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte(text), 0o600))
	}
	c, err := config.Parse([]byte(cfg), dir)
	require.NoError(t, err)
	return Generate(context.Background(), c, WithSpec([]byte(storeSpec)))
}

func TestGenerateWithExtraFiles(t *testing.T) {
	t.Parallel()

	res, err := generateExtra(t, `package: api
output: {file: ./api/gen.go}
server: {framework: chi, name: Pets}
extra-files:
  ./routes/routes.go: {file: ./tmpl/routes.tmpl}
  ./api/types.go: "var Types = []string{ {{range .Types}}{{quote .Name}}, {{end}} }"
`, map[string]string{"tmpl/routes.tmpl": routesTemplate})

	require.NoError(t, err)
	byPath := make(map[string]File, len(res.Files))
	for _, f := range res.Files {
		byPath[filepath.Base(filepath.Dir(f.Path))+"/"+filepath.Base(f.Path)] = f
	}
	routes, types := byPath["routes/routes.go"], byPath["api/types.go"]
	assert.Equal(t, []string{"./routes/routes.go"}, routes.Parts)
	assert.Equal(t, "routes", routes.Package)
	assert.Equal(t, FileGenerated, routes.Kind)
	assert.Equal(t, `// Code generated by mockzilla-codegen. DO NOT EDIT.

package routes

import (
	"net/http"

	"example.com/work/api"
)

// Routes maps every routed operation to its method and path.
var Routes = map[string][2]string{
	"ListPets":  {"GET", "/pets"},
	"CreatePet": {"POST", "/pets"},
	"DeletePet": {"DELETE", "/pets/{id}"},
	"Health":    {"GET", "/health"},
}

// Handler returns the router of svc.
func Handler(svc api.PetsInterface) http.Handler {
	return api.NewRouter(svc)
}
`, string(routes.Content))
	assert.Equal(t, "api", types.Package)
	assert.Contains(t, string(types.Content), "\nvar Types = []string{\"Pet\", ")
}

