const petSpec = `openapi: 3.1.0
info: {title: pets, version: "1"}
paths: {}
components:
  schemas:
    Pet:
      type: object
      properties:
        name: {type: string}
`

var errParse = errors.New("parse failed")

// failingParse reads specs like the real provider but fails to parse them.
type failingParse struct {
	provider.Provider
}

func (failingParse) Parse(context.Context, []byte, provider.ParseOptions) (*spec.Document, []diag.Diagnostic, error) {
	return nil, nil, errParse
}

// examples returns the config files of the golden examples. Those under plugin/ need a plugin of
// the examples module, so their own tests generate them.
func examples(t *testing.T) []string {
	t.Helper()

	root := filepath.Join("..", "..", "examples")
	paths, err := filepath.Glob(filepath.Join(root, "*", "*", "codegen.yaml"))
	require.NoError(t, err)
	nested, err := filepath.Glob(filepath.Join(root, "*", "*", "*", "codegen.yaml"))
	require.NoError(t, err)
	paths = slices.DeleteFunc(append(paths, nested...), func(p string) bool { return strings.HasPrefix(exampleName(p), "plugin/") })
	require.NotEmpty(t, paths)
	return paths
}

// exampleName is the path of an example inside examples/.
func exampleName(path string) string {
	rel, _ := filepath.Rel(filepath.Join("..", "..", "examples"), filepath.Dir(path))
	return filepath.ToSlash(rel)
}

// TestExamples compares every example with a fresh run. UPDATE=1 writes the run instead.
func TestExamples(t *testing.T) {
	t.Parallel()

	for _, path := range examples(t) {
		t.Run(exampleName(path), func(t *testing.T) {
			t.Parallel()

			cfg, err := config.Load(path)
			require.NoError(t, err)
			res, err := Generate(context.Background(), cfg)
			require.NoError(t, err)

			if os.Getenv("UPDATE") != "" {
				_, err = Write(res, WriteOptions{OverwriteScaffolds: true})
				require.NoError(t, err)
				return
			}
			for _, f := range res.Files {
				want, readErr := os.ReadFile(f.Path)
				require.NoError(t, readErr, "run make examples")
				assert.Equal(t, string(want), string(f.Content), f.Path)
			}
		})
	}
}

func TestExamplesAreDeterministic(t *testing.T) {
	t.Parallel()

	for _, path := range examples(t) {
		t.Run(exampleName(path), func(t *testing.T) {
			t.Parallel()

			cfg, err := config.Load(path)
			require.NoError(t, err)

			var first *Result
			for range 3 {
				res, genErr := Generate(context.Background(), cfg)
				require.NoError(t, genErr)
				if first == nil {
					first = res
					continue
				}
				assert.Equal(t, first, res)
			}
		})
	}
}

func TestGenerate(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	cfg, err := config.Parse([]byte("package: pets\noutput: {file: ./api/gen.go, format: false}\n"), dir)
	require.NoError(t, err)

	res, err := Generate(context.Background(), cfg, WithSpec([]byte(petSpec)))

	require.NoError(t, err)
	assert.Equal(t, &Result{
		Files: []File{{
			Path:    filepath.Join(dir, "api", "gen.go"),
			Package: "pets",
			Parts:   []string{"models.types", "models.enums", "models.unions", "models.params", "models.bodies", "models.responses"},
			Content: []byte("// Code generated by mockzilla-codegen. DO NOT EDIT.\n\npackage pets\n\ntype Pet struct {\n" +
				"\tName *string `json:\"name,omitempty\"`\n}\n"),
		}},
		Diagnostics: []Diagnostic{{
			Severity: SeverityInfo,
			Code:     "prune-skipped",
			Line:     1,
			Col:      1,
			Message:  "the spec has no operations, so nothing is pruned",
		}},
	}, res)
}

func TestGenerateErrors(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name    string
		cfg     string
		edit    func(cfg *config.Config)
		setup   func(t *testing.T, dir string)
		opts    []Option
		wantErr error
		wantMsg string
	}{
		{
			name:    "Invalid config",
			edit:    func(cfg *config.Config) { cfg.Models.IntType = "int8" },
			wantErr: config.ErrInvalid,
		},
		{
			name:    "No spec",
			wantErr: prepare.ErrNoSpec,
		},
		{
			name:    "Spec that does not parse",
			opts:    []Option{withProvider(failingParse{Provider: libopenapi.New()})},
			wantErr: errParse,
		},
		{
			name: "Unreadable go.mod",
			setup: func(t *testing.T, dir string) {
				t.Helper()
				require.NoError(t, os.Mkdir(filepath.Join(dir, "go.mod"), 0o750))
			},
			wantErr: layout.ErrModule,
		},
		{
			name:    "Selector that matches no part",
			cfg:     "output: {files: {./server.go: [server]}}\n",
			wantErr: layout.ErrUnknownSelector,
		},
		{
			name:    "Template override of an unknown block",
			cfg:     "templates: {models.struct: x}\n",
			wantErr: config.ErrInvalid,
			wantMsg: "invalid config: templates.models.struct: unknown block; the blocks are " +
				"server.request-options-extra, server.response-data-extra, server.router-extra, server.service-header",
		},
		{
			name:    "Template override of a server block without a server",
			cfg:     "templates: {server.service-header: x}\n",
			wantErr: config.ErrInvalid,
			wantMsg: "invalid config: templates.server.service-header: needs a server block",
		},
		{
			name:    "Template override file that is missing",
			cfg:     "server: {framework: chi}\ntemplates: {server.service-header: ./header.tmpl}\n",
			wantErr: ErrTemplateFile,
		},
		{
			name:    "Template override that is a path of another ending",
			cfg:     "server: {framework: chi}\ntemplates: {server.service-header: ./header.gotmpl, server.router-extra: ../routes.txt}\n",
			wantErr: config.ErrInvalid,
			wantMsg: `invalid config: templates.server.router-extra: "../routes.txt" is a path, and a template file has to end in .tmpl; ` +
				`templates.server.service-header: "./header.gotmpl" is a path, and a template file has to end in .tmpl`,
		},
		{
			name:    "Template override that reads a key the user-context does not have",
			cfg:     "server: {framework: chi}\nuser-context: {owner: platform}\ntemplates: {server.service-header: \"// Owned by {{.User.team}}.\"}\n",
			wantErr: render.ErrExecute,
			wantMsg: `./gen.go: render: template: server.service-header:1:19: executing "server.service-header" at <.User.team>: map has no entry for key "team"`,
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			dir := t.TempDir()
			if tc.setup != nil {
				tc.setup(t, dir)
			}
			cfg, err := config.Parse([]byte(tc.cfg), dir)
			require.NoError(t, err)
			if tc.edit != nil {
				tc.edit(cfg)
			}
			opts := tc.opts
			if tc.name != "No spec" {
				opts = append(opts, WithSpec([]byte(petSpec)))
			}

			res, err := Generate(context.Background(), cfg, opts...)

			require.ErrorIs(t, err, tc.wantErr)
			if tc.wantMsg != "" {
				require.EqualError(t, err, tc.wantMsg)
			}
			assert.Nil(t, res)
		})
	}
}

