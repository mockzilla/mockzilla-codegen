func TestGenerationRenderErrors(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name    string
		tmpl    string
		wantErr error
	}{
		{name: "Part template that fails", tmpl: "{{.Missing}}", wantErr: render.ErrExecute},
		{name: "Part that is no Go", tmpl: "type {", wantErr: gocode.ErrFormat},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			cfg, err := config.Parse(nil, "/work")
			require.NoError(t, err)
			gen := models.New(&gomodel.Model{})
			lay, err := layout.Plan(cfg, gen.Parts(), layout.Module{})
			require.NoError(t, err)
			set := models.Templates()
			set.FS = fstest.MapFS{"part.tmpl": {Data: []byte(tc.tmpl)}}
			engine, err := render.New([]render.Set{set}, render.Options{Format: true})
			require.NoError(t, err)
			g := &generation{cfg: cfg, gen: gen, lay: lay, engine: engine}

			err = g.render()

			require.ErrorIs(t, err, tc.wantErr)
			assert.ErrorContains(t, err, "./gen.go: ")
		})
	}
}

func TestGenerateReportsTheClientDiagnostics(t *testing.T) {
	t.Parallel()

	const streamSpec = `openapi: 3.1.0
info: {title: events, version: "1"}
paths:
  /events:
    get:
      operationId: getEvents
      responses:
        "200":
          description: events
          content:
            text/event-stream: {schema: {type: object, properties: {seq: {type: integer}}}}
`
	dir := t.TempDir()
	cfg, err := config.Parse([]byte("package: events\nclient: {}\noutput: {file: ./api/gen.go}\n"), dir)
	require.NoError(t, err)

	res, err := Generate(context.Background(), cfg, WithSpec([]byte(streamSpec)))

	require.NoError(t, err)
	assert.Contains(t, res.Diagnostics, Diagnostic{
		Severity: SeverityWarning,
		Code:     "stream-only",
		Pointer:  "/paths/~1events/get",
		Line:     5,
		Col:      5,
		Message:  "GetEvents answers only as text/event-stream, which GetEvents reads whole; set client.streaming to read it as it arrives",
	})
}

func TestGenerateReportsTheMCPDiagnostics(t *testing.T) {
	t.Parallel()

	const toolSpec = `openapi: 3.1.0
info: {title: tools, version: "1"}
paths:
  /ping:
    get:
      operationId: ping
      x-mcp: {name: "ping me"}
      responses:
        "204": {description: pong}
`
	dir := t.TempDir()
	cfg, err := config.Parse([]byte("package: tools\nclient: {}\nmcp: {}\noutput: {file: ./api/gen.go}\n"), dir)
	require.NoError(t, err)

	res, err := Generate(context.Background(), cfg, WithSpec([]byte(toolSpec)))

	require.NoError(t, err)
	assert.Contains(t, res.Diagnostics, Diagnostic{
		Severity: SeverityWarning,
		Code:     "mcp-tool-name",
		Pointer:  "/paths/~1ping/get/x-mcp/name",
		Line:     5,
		Col:      5,
		Message:  `x-mcp.name "ping me" is no tool name, which has letters, digits, _ - and . up to 128 characters; the tool is named "ping"`,
	})
	assert.Equal(t, []string{
		"models.types", "models.enums", "models.unions", "models.params", "models.bodies", "models.responses",
		"client.core", "client.options", "client.operations", "mcp.inputs", "mcp.tools",
	}, res.Files[0].Parts)
}
