func TestLoad(t *testing.T) {
	t.Parallel()

	dir := filepath.Join(t.TempDir(), "services", "pet-store")
	require.NoError(t, os.MkdirAll(dir, 0o750))
	path := filepath.Join(dir, "codegen.yaml")
	require.NoError(t, os.WriteFile(path, []byte("spec: {path: ./openapi.yaml}\n"), 0o600))

	cfg, err := Load(path)

	require.NoError(t, err)
	assert.Equal(t, &Config{
		Spec:    Spec{Path: "./openapi.yaml", Prune: new(true)},
		Package: "petstore",
		Header:  defaultHeader,
		Naming:  Naming{EnumPrefix: new(true)},
		Models:  &Models{IntType: "int", Descriptions: new(true)},
		Output:  Output{File: "./gen.go", Format: new(true)},
		dir:     dir,
	}, cfg)
	assert.Equal(t, filepath.Join(dir, "openapi.yaml"), cfg.Resolve(cfg.Spec.Path))
}

func TestLoadMissingFile(t *testing.T) {
	t.Parallel()

	_, err := Load(filepath.Join(t.TempDir(), "codegen.yaml"))

	require.ErrorIs(t, err, ErrRead)
	assert.ErrorIs(t, err, fs.ErrNotExist)
}

func TestParse(t *testing.T) {
	t.Parallel()

	full, readErr := os.ReadFile(filepath.Join("testdata", "full.yaml"))
	require.NoError(t, readErr)

	tests := []struct {
		name    string
		src     string
		want    *Config
		wantErr error
		wantMsg string
	}{
		{
			name: "Empty file gives defaults",
			src:  "",
			want: &Config{
				Spec:    Spec{Prune: new(true)},
				Package: "work",
				Header:  defaultHeader,
				Naming:  Naming{EnumPrefix: new(true)},
				Models:  &Models{IntType: "int", Descriptions: new(true)},
				Output:  Output{File: "./gen.go", Format: new(true)},
				dir:     "/work",
			},
		},
		{
			name: "Comment-only file gives defaults",
			src:  "# nothing yet\n",
			want: defaulted(Config{dir: "/work"}),
		},
		{
			name: "Null document gives defaults",
			src:  "~\n",
			want: defaulted(Config{dir: "/work"}),
		},
		{
			name: "Full example decodes every block",
			src:  string(full),
			want: &Config{
				Spec: Spec{
					Path:     "./openapi.yaml",
					Overlays: []string{"./overlays/go-names.yaml"},
					Filter: Filter{
						Include: FilterSet{
							Paths:            []string{"/pets"},
							Tags:             []string{"pets"},
							OperationIDs:     []string{"listPets"},
							Webhooks:         []string{"newPet"},
							Extensions:       []string{"x-public"},
							SchemaProperties: map[string][]string{"Pet": {"name", "tag"}},
						},
						Exclude: FilterSet{Tags: []string{"internal"}},
					},
					Prune:    new(true),
					Simplify: &Simplify{Unions: true, OptionalProperties: &OptionalProperties{Min: 1, Max: 3, Seed: 1}},
				},
				Package: "api",
				Header:  "Copyright 2026 Acme. Code generated by mockzilla-codegen. DO NOT EDIT.",
				Naming:  Naming{Initialisms: []string{"PSP"}, EnumPrefix: new(true)},
				Imports: []Import{{Package: "github.com/google/uuid"}, {Package: "example.com/shop/tenant", Alias: "tn"}},
				Models: &Models{
					IntType:      "int64",
					Descriptions: new(false),
					ExtraTags:    []string{"yaml"},
					Validation:   ModelValidation{Response: true},
					ErrorMapping: map[string]string{"ErrorResponse": "error.message"},
				},
				Server: &Server{
					Framework:          "chi",
					Name:               "PetService",
					Validation:         ServerValidation{Request: true},
					MultipartMaxMemory: 64 << 20,
					Scaffold: Scaffold{
						Service:    "./api/service.go",
						Middleware: "./api/middleware.go",
						Main:       "./cmd/server/main.go",
						Port:       9090,
						Timeout:    Duration(45 * time.Second),
					},
				},
				Client: &Client{Name: "PetClient", Timeout: Duration(5 * time.Second), WithResponse: true, Streaming: true},
				MCP:    &MCP{},
				Templates: map[string]Template{
					"server.service-header":        {File: "./templates/header.tmpl"},
					"server.request-options-extra": {Text: "Tenant tn.ID"},
				},
				UserContext: map[string]any{"owner": "platform"},
				Output: Output{
					File:     "./api/gen.go",
					Files:    map[string][]string{"./api/server.gen.go": {"server"}},
					Packages: map[string]string{"./models": "models"},
					Format:   new(true),
				},
				dir: "/work",
			},
		},
		{
			name: "Block key with no value turns the block on",
			src:  "client:\nmcp:\n",
			want: defaulted(Config{Client: &Client{}, MCP: &MCP{}, dir: "/work"}),
		},
		{
			name: "Merge key fills a list item",
			src:  "user-context:\n  base: &base {package: example.com/x}\nimports:\n  - <<: *base\n    alias: x\n",
			want: defaulted(Config{
				Imports:     []Import{{Package: "example.com/x", Alias: "x"}},
				UserContext: map[string]any{"base": map[string]any{"package": "example.com/x"}},
				dir:         "/work",
			}),
		},
		{
			name:    "YAML syntax error is a decode error",
			src:     "spec: [\n",
			wantErr: ErrDecode,
			wantMsg: "decode config: go-yaml load error in parser (while parsing a flow node) at L2.C1: did not find expected node content",
		},
		{
			name:    "Wrong value type is a decode error",
			src:     "server: {framework: chi, scaffold: {port: abc}}\n",
			wantErr: ErrDecode,
			wantMsg: "decode config: yaml: construct errors: line 1: cannot construct !!str `abc` into int",
		},
		{
			name:    "Bad byte size is a decode error",
			src:     "server: {framework: chi, multipart-max-memory: 32mb}\n",
			wantErr: ErrByteSize,
			wantMsg: "decode config: yaml: construct errors: line 1: invalid byte size \"32mb\", want an integer or a size such as 512KB or 32MB",
		},
		{
			name:    "Top-level list is a decode error",
			src:     "- spec\n",
			wantErr: ErrDecode,
			wantMsg: "decode config: yaml: construct errors: line 1: cannot construct !!seq into config.Config",
		},
		{
			name:    "Unknown keys are listed with their paths",
			src:     "spec: {filter: {include: {tag: [a]}}}\nserver: {framework: chi, port: 1}\n",
			wantErr: ErrUnknownKey,
			wantMsg: "unknown config key: spec.filter.include.tag, server.port",
		},
		{
			name:    "Invalid values are a validation error",
			src:     "server: {framework: express}\n",
			wantErr: ErrInvalid,
			wantMsg: `invalid config: server.framework: "express" is not one of beego, chi, echo, echo-v5, fasthttp, fiber, gin, go-zero, goframe, gorilla-mux, hertz, iris, kratos, std-http`,
		},
		{
			name:    "Template that is a path and no file is a validation error",
			src:     "templates: {server.service-header: ./header.tmpl, server.router-extra: }\n",
			wantErr: ErrInvalid,
			wantMsg: `invalid config: templates.server.router-extra: is empty, want the text or {file: <path>}; ` +
				`templates.server.service-header: "./header.tmpl" is a path, want {file: ./header.tmpl}`,
		},
		{
			name:    "Unknown key in a template is listed with its path",
			src:     "templates: {server.service-header: {fiel: ./header.tmpl}}\n",
			wantErr: ErrUnknownKey,
			wantMsg: "unknown config key: templates.server.service-header.fiel",
		},
		{
			name:    "List where a template belongs is a decode error",
			src:     "templates: {server.service-header: [a]}\n",
			wantErr: ErrDecode,
			wantMsg: "decode config: yaml: construct errors: line 1: cannot construct !!seq into config.template",
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			cfg, err := Parse([]byte(tc.src), "/work")

			if tc.wantErr != nil {
				require.ErrorIs(t, err, tc.wantErr)
				require.EqualError(t, err, tc.wantMsg)
				assert.Nil(t, cfg)
				return
			}
			require.NoError(t, err)
			assert.Equal(t, tc.want, cfg)
		})
	}
}

func TestReadmeShowsTheFullExample(t *testing.T) {
	t.Parallel()

	readme, err := os.ReadFile(filepath.Join("..", "..", "README.md"))
	require.NoError(t, err)
	full, err := os.ReadFile(filepath.Join("testdata", "full.yaml"))
	require.NoError(t, err)

	assert.Contains(t, string(readme), "```yaml\n"+string(full)+"```\n")
}

func defaulted(c Config) *Config {
	c.applyDefaults()
	return &c
}
