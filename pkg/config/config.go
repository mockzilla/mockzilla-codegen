// Package config loads, checks and describes the mockzilla-codegen config file.
package config

import (
	"cmp"
	"path/filepath"
	"slices"
	"strings"
	"time"

	"github.com/mockzilla/mockzilla-codegen/internal/naming"
)

// defaultHeader is the line Go tools look for to treat a file as generated.
const defaultHeader = "Code generated by mockzilla-codegen. DO NOT EDIT."

// Config is the whole mockzilla-codegen config file.
type Config struct {
	Spec        Spec                `yaml:"spec" desc:"Input spec and how to prepare it before generation."`
	Package     string              `yaml:"package" desc:"Go package of the default output file. Defaults to its folder name."`
	Header      string              `yaml:"header" desc:"Comment at the top of every generated file. Defaults to the line that marks it generated: Code generated by mockzilla-codegen. DO NOT EDIT."`
	Naming      Naming              `yaml:"naming" desc:"How Go names are built."`
	Imports     []Import            `yaml:"imports" desc:"Packages that template overrides and x-go-type refer to. A generated file imports one when its code names it."`
	Models      *Models             `yaml:"models" desc:"Models generation. Always on."`
	Server      *Server             `yaml:"server" desc:"Server generation. Present means generate."`
	Client      *Client             `yaml:"client" desc:"Client generation. Present means generate."`
	MCP         *MCP                `yaml:"mcp" desc:"MCP server generation. Present means generate. Needs client."`
	Templates   map[string]Template `yaml:"templates" desc:"Template overrides, keyed by block name: the text, or the file that holds it."`
	UserContext map[string]any      `yaml:"user-context" desc:"Free-form values passed to templates."`
	Output      Output              `yaml:"output" desc:"Where generated files go."`

	dir string
}

// Resolve returns p joined with the directory of the config file. Absolute paths and URLs come
// back unchanged.
func (c *Config) Resolve(p string) string {
	if filepath.IsAbs(p) || strings.Contains(p, "://") {
		return p
	}
	return filepath.Join(c.dir, p)
}

// Validate checks the config and returns a *ValidationError listing every problem, or nil.
// A spec path is not required here: it can come from the command line or from memory.
func (c *Config) Validate() error {
	issues := slices.Concat(
		checkPackage("package", c.Package),
		checkImports(c.Imports),
		checkSimplify(c.Spec.Simplify),
		checkModels(c.Models),
		checkServer(c.Server),
		checkMCP(c.MCP, c.Client),
		checkTemplates(c.Templates),
		checkOutput(c.Output),
	)
	if len(issues) == 0 {
		return nil
	}
	return &ValidationError{Issues: issues}
}

func (c *Config) applyDefaults() {
	c.Output.File = cmp.Or(c.Output.File, "./gen.go")
	c.Output.Format = cmp.Or(c.Output.Format, new(true))
	c.Package = cmp.Or(c.Package, naming.Package(c.Resolve(filepath.Dir(c.Output.File))))
	c.Header = cmp.Or(c.Header, defaultHeader)
	c.Spec.Prune = cmp.Or(c.Spec.Prune, new(true))
	c.Naming.EnumPrefix = cmp.Or(c.Naming.EnumPrefix, new(true))

	c.Models = cmp.Or(c.Models, &Models{})
	c.Models.IntType = cmp.Or(c.Models.IntType, "int")
	c.Models.Descriptions = cmp.Or(c.Models.Descriptions, new(true))

	if s := c.Server; s != nil {
		s.Name = cmp.Or(s.Name, "Service")
		s.MultipartMaxMemory = cmp.Or(s.MultipartMaxMemory, 32<<20)
		s.Scaffold.Port = cmp.Or(s.Scaffold.Port, 8080)
		s.Scaffold.Timeout = cmp.Or(s.Scaffold.Timeout, Duration(30*time.Second))
	}

	if cl := c.Client; cl != nil {
		cl.Name = cmp.Or(cl.Name, "Client")
		cl.Timeout = cmp.Or(cl.Timeout, Duration(3*time.Second))
	}
}
