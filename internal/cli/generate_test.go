func TestOutputDiagnostics(t *testing.T) {
	t.Parallel()

	list := []codegen.Diagnostic{
		{Severity: codegen.SeverityWarning, Code: "filter-empty", Message: "the filter removed every operation"},
		{Severity: codegen.SeverityInfo, Code: "prune-skipped", File: "/work/api.yaml", Message: "nothing is pruned"},
		{Severity: codegen.SeverityError, Code: "build-issue", File: "https://example.com/api.yaml", Line: 3, Col: 1, Pointer: "/paths", Message: "bad"},
	}
	tests := []struct {
		name      string
		isVerbose bool
		want      string
	}{
		{
			name: "Warnings and errors",
			want: "warning filter-empty: the filter removed every operation\n" +
				"https://example.com/api.yaml:3:1: error build-issue: bad [/paths]\n",
		},
		{
			name:      "Verbose adds info",
			isVerbose: true,
			want: "warning filter-empty: the filter removed every operation\n" +
				"api.yaml: info prune-skipped: nothing is pruned\n" +
				"https://example.com/api.yaml:3:1: error build-issue: bad [/paths]\n",
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			var stderr strings.Builder
			o := &output{dir: "/work", stderr: &stderr}
			o.diagnostics(list, tc.isVerbose)

			assert.Equal(t, tc.want, stderr.String())
		})
	}
}

func TestOutputCheckSkipsScaffolds(t *testing.T) {
	t.Parallel()

	var stdout strings.Builder
	o := &output{dir: "/work", stdout: &stdout}
	res := &codegen.Result{Files: []codegen.File{{Path: filepath.Join(t.TempDir(), "main.go"), Kind: codegen.FileScaffold}}}

	assert.Equal(t, ExitOK, o.check(res))
	assert.Empty(t, stdout.String())
}
