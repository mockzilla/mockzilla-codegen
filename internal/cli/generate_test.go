const petSpec = `openapi: 3.1.0
info: {title: pets, version: "1"}
paths: {}
components:
  schemas:
    Pet:
      type: object
      properties:
        user_id: {type: string}
        userId: {type: string}
`

const petGo = `// Code generated by mockzilla-codegen. DO NOT EDIT.

package api

type Pet struct {
	UserID  *string ` + "`json:\"user_id,omitempty\"`" + `
	UserID2 *string ` + "`json:\"userId,omitempty\"`" + `
}
`

const petClash = `api.yaml:10:9: info name-clash: "UserID" is used by /components/schemas/Pet/properties/user_id, ` +
	`renamed to "UserID2" [/components/schemas/Pet/properties/userId]` + "\n"

// project writes a config and the pet spec to a new folder and returns the config path.
func project(t *testing.T, cfg string) string {
	t.Helper()

	dir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(dir, "api.yaml"), []byte(petSpec), 0o600))
	path := filepath.Join(dir, "codegen.yml")
	require.NoError(t, os.WriteFile(path, []byte(cfg), 0o600))
	return path
}

func TestGenerate(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name       string
		flags      []string
		wantStdout string
		wantStderr string
	}{
		{name: "Quiet by default"},
		{
			name:  "Verbose prints info and the files",
			flags: []string{"-v"},
			wantStdout: "FILE    PACKAGE  PARTS                                                                                 ACTION\n" +
				"gen.go  api      models.types,models.enums,models.unions,models.params,models.bodies,models.responses  write\n",
			wantStderr: "api.yaml:1:1: info prune-skipped: the spec has no operations, so nothing is pruned\n" + petClash,
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			cfg := project(t, "spec: {path: api.yaml}\npackage: api\n")

			code, stdout, stderr := run(t, append([]string{"generate", "-c", cfg}, tc.flags...)...)

			assert.Equal(t, ExitOK, code)
			assert.Equal(t, tc.wantStdout, stdout)
			assert.Equal(t, tc.wantStderr, stderr)
			got, err := os.ReadFile(filepath.Join(filepath.Dir(cfg), "gen.go"))
			require.NoError(t, err)
			assert.Equal(t, petGo, string(got))
		})
	}
}

func TestGenerateSpecArgument(t *testing.T) {
	t.Parallel()

	cfg := project(t, "package: api\noutput: {file: ./out/gen.go}\n")
	spec := filepath.Join(filepath.Dir(cfg), "api.yaml")

	code, _, stderr := run(t, "generate", spec, "-c", cfg)

	assert.Equal(t, ExitOK, code, stderr)
	got, err := os.ReadFile(filepath.Join(filepath.Dir(cfg), "out", "gen.go"))
	require.NoError(t, err)
	assert.Equal(t, petGo, string(got))
}

func TestGenerateDryRun(t *testing.T) {
	t.Parallel()

	cfg := project(t, "spec: {path: api.yaml}\noutput:\n  file: ./api/gen.go\n  files: {./api/enums.go: [models.enums]}\n")

	code, stdout, stderr := run(t, "generate", "-c", cfg, "-dry-run")

	assert.Equal(t, ExitOK, code)
	assert.Equal(t, "FILE          PACKAGE  PARTS                                                                    ACTION\n"+
		"api/enums.go  api      models.enums                                                             write\n"+
		"api/gen.go    api      models.types,models.unions,models.params,models.bodies,models.responses  write\n", stdout)
	assert.Empty(t, stderr)
	assert.NoDirExists(t, filepath.Join(filepath.Dir(cfg), "api"))
}

func TestGenerateCheck(t *testing.T) {
	t.Parallel()

	cfg := project(t, "spec: {path: api.yaml}\npackage: api\n")
	gen := filepath.Join(filepath.Dir(cfg), "gen.go")

	code, stdout, _ := run(t, "generate", "-c", cfg, "-check")
	assert.Equal(t, ExitFail, code)
	assert.Equal(t, "generated files are out of date, run mockzilla-codegen generate:\n  gen.go: missing\n", stdout)

	code, _, _ = run(t, "generate", "-c", cfg)
	require.Equal(t, ExitOK, code)
	code, stdout, _ = run(t, "generate", "-c", cfg, "-check")
	assert.Equal(t, ExitOK, code)
	assert.Empty(t, stdout)

	require.NoError(t, os.WriteFile(gen, []byte("package api\n"), 0o600))
	code, stdout, _ = run(t, "generate", "-c", cfg, "-check")
	assert.Equal(t, ExitFail, code)
	assert.Equal(t, "generated files are out of date, run mockzilla-codegen generate:\n  gen.go: differs\n", stdout)
}

func TestGenerateFailures(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name       string
		cfg        string
		setup      func(t *testing.T, dir string)
		args       []string
		wantCode   int
		wantStderr string
	}{
		{
			name:       "Two specs",
			args:       []string{"a.yaml", "b.yaml"},
			wantCode:   ExitUsage,
			wantStderr: "mockzilla-codegen: generate takes at most one spec, got 2\n",
		},
		{
			name:       "Dry run and check together",
			args:       []string{"-dry-run", "-check"},
			wantCode:   ExitUsage,
			wantStderr: "mockzilla-codegen: -dry-run and -check do not go together\n",
		},
		{
			name:     "Unknown flag",
			args:     []string{"-x"},
			wantCode: ExitUsage,
		},
		{
			name: "Help flag",
			args: []string{"-h"},
		},
		{
			name:       "Invalid config",
			cfg:        "models: {int-type: int8}\n",
			wantCode:   ExitFail,
			wantStderr: "mockzilla-codegen: invalid config: models.int-type: \"int8\" is not one of int, int32, int64\n",
		},
		{
			name:       "No spec",
			cfg:        "package: api\n",
			wantCode:   ExitFail,
			wantStderr: "mockzilla-codegen: no spec: set spec.path or pass the spec in memory\n",
		},
		{
			name: "Output that cannot be written",
			cfg:  "spec: {path: api.yaml}\noutput: {file: ./blocked/gen.go}\n",
			setup: func(t *testing.T, dir string) {
				t.Helper()
				require.NoError(t, os.WriteFile(filepath.Join(dir, "blocked"), nil, 0o600))
			},
			wantCode:   ExitFail,
			wantStderr: "mockzilla-codegen: write generated file: mkdir {dir}/blocked: not a directory\n",
		},
		{
			name: "Output that cannot be read for a check",
			cfg:  "spec: {path: api.yaml}\n",
			setup: func(t *testing.T, dir string) {
				t.Helper()
				require.NoError(t, os.Mkdir(filepath.Join(dir, "gen.go"), 0o750))
			},
			args:       []string{"-check"},
			wantCode:   ExitFail,
			wantStderr: "mockzilla-codegen: read {dir}/gen.go: is a directory\n",
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			cfg := project(t, tc.cfg)
			dir := filepath.Dir(cfg)
			if tc.setup != nil {
				tc.setup(t, dir)
			}

			code, _, stderr := run(t, append([]string{"generate", "-c", cfg}, tc.args...)...)

			assert.Equal(t, tc.wantCode, code)
			if tc.wantStderr != "" {
				assert.Equal(t, strings.ReplaceAll(tc.wantStderr, "{dir}", dir), stderr)
			}
		})
	}
}

